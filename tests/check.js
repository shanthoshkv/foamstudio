// Fast quality gate (no OpenFOAM needed): golden snapshots + invariants + determinism + spec round-trip.
// usage: node check.js            -> compare against tests/golden, exit 1 on any failure
//        node check.js --update   -> rewrite golden snapshots (review the git diff!)
const fs = require('fs');
const path = require('path');
const { generate } = require('./gen');
const { loadGenerator } = require('./headless');

const UPDATE = process.argv.includes('--update');
const GOLDEN = path.join(__dirname, 'golden');
const VERS = ['2412', '12', '14', '2006', '9'];      // ESI current/old, Foundation module era/new/pre-module
const SOURCES = ['gen_fn.js', 'extra_fn.js'];
let failures = 0;
const fail = (m) => { failures++; console.log('FAIL ' + m); };

// strip the provenance line so golden diffs show real content changes, not hash churn
const norm = t => t.replace(/^\/\/ Generated by OpenFOAM Case Generator.*$/m, '// <provenance>');

// ── 1. invariants on every generated file ──
function invariants(name, files) {
  for (const [p, t] of Object.entries(files)) {
    if (/\bundefined\b|\bNaN\b|\[object /.test(t)) fail(`${name} ${p}: contains undefined/NaN/[object]`);
    if (/^FoamFile/m.test(t) && !/Generated by OpenFOAM Case Generator \S+ \| spec [0-9a-f]{8}/.test(t)) fail(`${name} ${p}: missing provenance line`);
    if (/^FoamFile/m.test(t) && (t.match(/\{/g) || []).length !== (t.match(/\}/g) || []).length) fail(`${name} ${p}: unbalanced braces`);
    if (p.endsWith('fvSchemes') && /nuEff\*dev\(/.test(t)) fail(`${name} ${p}: uses dev( instead of dev2(`);
    if (/\/Allrun$/.test(p) && !/^#!\/bin\/sh/.test(t)) fail(`${name} ${p}: Allrun without shebang`);
    if (p.endsWith('case.json')) { try { JSON.parse(t); } catch (e) { fail(`${name} case.json invalid JSON`); } }
  }
}

// ── 2. golden snapshots + determinism ──
fs.mkdirSync(GOLDEN, { recursive: true });
for (const v of VERS) {
  const a = {}, b = {};
  for (const s of SOURCES) { Object.assign(a, generate(s, [v])); Object.assign(b, generate(s, [v])); }
  const snap = {};
  for (const [name, c] of Object.entries(a)) {
    invariants(name, c.files);
    const other = b[name];
    for (const p of Object.keys(c.files)) if (!other || other.files[p] !== c.files[p]) fail(`${name} ${p}: non-deterministic output`);
    snap[name] = Object.fromEntries(Object.entries(c.files).map(([p, t]) => [p.slice(name.length + 1), norm(t)]));
  }
  const gf = path.join(GOLDEN, `v${v}.json`);
  if (UPDATE || !fs.existsSync(gf)) { fs.writeFileSync(gf, JSON.stringify(snap, null, 1) + '\n'); console.log(`wrote ${path.basename(gf)} (${Object.keys(snap).length} cases)`); continue; }
  const gold = JSON.parse(fs.readFileSync(gf, 'utf8'));
  for (const name of new Set([...Object.keys(gold), ...Object.keys(snap)])) {
    if (!gold[name]) { fail(`v${v} ${name}: new case not in golden (run --update)`); continue; }
    if (!snap[name]) { fail(`v${v} ${name}: case disappeared`); continue; }
    for (const p of new Set([...Object.keys(gold[name]), ...Object.keys(snap[name])])) {
      const x = gold[name][p], y = snap[name][p];
      if (x === y) continue;
      if (x === undefined || y === undefined) { fail(`v${v} ${name}/${p}: file ${x === undefined ? 'added' : 'removed'}`); continue; }
      const xl = x.split('\n'), yl = y.split('\n');
      const i = xl.findIndex((l, k) => l !== yl[k]);
      fail(`v${v} ${name}/${p}: line ${i + 1}\n     - ${xl[i]}\n     + ${yl[i]}`);
    }
  }
}

// ── 3. case.json round-trip + validation ──
{
  const g = loadGenerator();
  g.setVersion(2412); g.setSolver('pimpleFoam'); g.setCaseName('rt');
  g.STATE.patches = [['inlet', 'inlet'], ['outlet', 'outlet'], ['rotor', 'wall'], ['AMI1', 'ami'], ['AMI2', 'ami'], ['frontAndBack', 'empty']].map(([n, r]) => g.ctx.makePatch(n, r));
  Object.assign(g.STATE, { motion: 'ami', rotRPM: 3000, turboPerf: true, nProcs: 4 });
  const A = g.buildCaseFiles('rt');
  const spec = JSON.parse(A['rt/case.json']);
  const h = loadGenerator();
  h.ctx.applySpec(spec);
  const B = h.buildCaseFiles('rt');
  const diff = Object.keys({ ...A, ...B }).filter(k => A[k] !== B[k]);
  if (diff.length) fail(`case.json round-trip changed: ${diff.join(', ')}`); else console.log('ok   case.json round-trip reproduces all files');
  const bad = [
    [{ ...spec, schema: 99 }, 'schema'], [{ ...spec, state: { ...spec.state, solver: 'fooFoam' } }, 'unknown solver'],
    [{ ...spec, state: { ...spec.state, patches: [{ name: 'a b', role: 'wall' }] } }, 'invalid name'],
    [{ ...spec, state: { ...spec.state, patches: [{ name: 'x', role: 'lid' }] } }, 'unknown role'],
    [{ ...spec, state: { ...spec.state, control: { ...spec.state.control, deltaT: 0 } } }, 'deltaT']
  ];
  if (h.ctx.validateSpec(spec).length) fail('valid spec rejected: ' + h.ctx.validateSpec(spec));
  for (const [s, why] of bad) if (!h.ctx.validateSpec(s).some(e => e.includes(why.split(' ')[0]) || e.includes(why))) fail(`validateSpec accepted bad spec (${why})`);
  console.log('ok   validateSpec accepts valid / rejects 5 malformed specs');
}

console.log(failures ? `\n${failures} FAILURE(S)` : '\nALL CHECKS PASSED');
process.exit(failures ? 1 : 0);
