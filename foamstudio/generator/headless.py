"""Run the case generator through Node. This module does not write dictionaries.

``tests/headless.js`` loads ``openfoam_case_generator.html``. Golden files were produced
by that Node host. A second JavaScript engine is not used.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

from foamstudio.core.runtime.model import format_argv, log_tail

NODE_INSTALL = (
    "Install Node.js 20 or newer and retry. https://nodejs.org/ "
    "Set FOAMSTUDIO_NODE to the node executable if it is not on PATH."
)
_PROVENANCE_LINE = re.compile(r"^// Generated by OpenFOAM Case Generator.*$", re.MULTILINE)


class GeneratorFailure(Exception):
    """Node or the generator script failed. The message includes the command, the log, and a fix."""

    def __init__(
        self,
        *,
        command: str,
        returncode: int,
        log_tail: str,
        suggestion: str,
    ) -> None:
        self.command = command
        self.returncode = returncode
        self.log_tail = log_tail
        self.suggestion = suggestion
        super().__init__(f"Command failed ({returncode}).\n{command}\n\n{log_tail}\n\n{suggestion}")


@dataclass(frozen=True)
class GeneratedCase:
    files: dict[str, str]
    command: str
    case_name: str


def repository_root() -> Path:
    override = os.environ.get("FOAMSTUDIO_REPO")
    candidates: list[Path] = []
    if override:
        candidates.append(Path(override))
    meipass = getattr(sys, "_MEIPASS", None)
    if isinstance(meipass, str):
        candidates.append(Path(meipass))
    candidates.append(Path(__file__).resolve().parents[2])
    candidates.append(Path.cwd())
    seen: set[Path] = set()
    for root in candidates:
        try:
            folder = root.resolve()
        except OSError:
            continue
        if folder in seen:
            continue
        seen.add(folder)
        if (folder / "openfoam_case_generator.html").is_file() and (
            folder / "tests" / "headless.js"
        ).is_file():
            return folder
    looked = ", ".join(str(path) for path in candidates) or "(none)"
    raise GeneratorFailure(
        command="node tests/headless.js",
        returncode=127,
        log_tail=f"openfoam_case_generator.html was not found. Looked in {looked}.",
        suggestion=(
            "Set FOAMSTUDIO_REPO to the checkout that contains "
            "openfoam_case_generator.html and tests/headless.js."
        ),
    )


def normalize_provenance(text: str) -> str:
    """Match tests/check.js so a spec hash change is not a dictionary change."""

    return _PROVENANCE_LINE.sub("// <provenance>", text)


def relativize(files: dict[str, str], case_name: str) -> dict[str, str]:
    prefix = case_name + "/"
    relative: dict[str, str] = {}
    for path, text in files.items():
        key = path[len(prefix) :] if path.startswith(prefix) else path
        relative[key] = normalize_provenance(text)
    return relative


def first_difference(expected: str, actual: str) -> str:
    expected_lines = expected.splitlines()
    actual_lines = actual.splitlines()
    limit = max(len(expected_lines), len(actual_lines))
    for index in range(limit):
        left = expected_lines[index] if index < len(expected_lines) else "<missing>"
        right = actual_lines[index] if index < len(actual_lines) else "<missing>"
        if left != right:
            return f"line {index + 1}\n     - {left}\n     + {right}"
    return "file contents differ"


def apply_command(spec_path: Path, *, case_name: str | None = None) -> str:
    return format_argv(_apply_argv(spec_path, case_name=case_name))


def apply_spec_text(
    spec_text: str,
    *,
    case_name: str | None = None,
    spec_path: Path | None = None,
    timeout: float = 120,
) -> GeneratedCase:
    cleanup: Path | None = None
    path = spec_path
    if path is None:
        path = _write_temp(spec_text, suffix=".json")
        cleanup = path
    try:
        return _apply_file(path, case_name=case_name, timeout=timeout)
    finally:
        if cleanup is not None:
            cleanup.unlink(missing_ok=True)


def apply_many(
    jobs: list[tuple[str, str]],
    *,
    timeout: float = 180,
) -> list[GeneratedCase]:
    """Apply each ``(case_name, spec_text)`` in one Node process."""

    if not jobs:
        raise GeneratorFailure(
            command="node tests/headless.js --apply-many",
            returncode=2,
            log_tail="(no output)",
            suggestion="Pass at least one case.json.",
        )
    payload = [{"name": name, "specText": text} for name, text in jobs]
    path = _write_temp(json.dumps(payload), suffix=".json")
    argv = _node_argv("--apply-many", str(path))
    command = format_argv(argv)
    try:
        completed = _run(argv, timeout=timeout)
        if completed.returncode != 0:
            raise _failed(
                command, completed, NODE_INSTALL if completed.returncode == 127 else _JS_FIX
            )
        try:
            data: object = json.loads(completed.stdout)
        except json.JSONDecodeError as exc:
            raise _failed(command, completed, _JSON_FIX) from exc
        if not isinstance(data, list):
            raise _failed(command, completed, _JSON_FIX)
        cases: list[GeneratedCase] = []
        for item in cast(list[object], data):
            if not isinstance(item, dict):
                raise _failed(command, completed, _JSON_FIX)
            entry = cast(dict[str, Any], item)
            name = entry.get("name")
            files = _as_files(entry.get("files"), command=command, completed=completed)
            if not isinstance(name, str) or not name:
                raise _failed(command, completed, _JSON_FIX)
            cases.append(GeneratedCase(files=files, command=command, case_name=name))
        if len(cases) != len(jobs):
            raise _failed(
                command,
                completed,
                "Node returned a different number of cases than were requested. "
                "There is no second dictionary writer.",
            )
        return cases
    finally:
        path.unlink(missing_ok=True)


def generate_table(
    fn_file: str = "gen_fn.js",
    versions: list[str] | None = None,
    *,
    timeout: float = 120,
) -> dict[str, Any]:
    if Path(fn_file).name != fn_file:
        raise GeneratorFailure(
            command="node tests/headless.js --generate",
            returncode=2,
            log_tail=fn_file,
            suggestion="Pass a file name inside tests/, such as gen_fn.js.",
        )
    chosen = versions or ["2412"]
    argv = _node_argv("--generate", fn_file, "--vers", ",".join(chosen))
    command = format_argv(argv)
    completed = _run(argv, timeout=timeout)
    if completed.returncode != 0:
        raise _failed(command, completed, NODE_INSTALL if completed.returncode == 127 else _JS_FIX)
    try:
        data: object = json.loads(completed.stdout)
    except json.JSONDecodeError as exc:
        raise _failed(command, completed, _JSON_FIX) from exc
    if not isinstance(data, dict):
        raise _failed(command, completed, _JSON_FIX)
    return cast(dict[str, Any], data)


def _apply_file(spec_path: Path, *, case_name: str | None, timeout: float) -> GeneratedCase:
    argv = _apply_argv(spec_path, case_name=case_name)
    command = format_argv(argv)
    completed = _run(argv, timeout=timeout)
    if completed.returncode != 0:
        raise _failed(command, completed, NODE_INSTALL if completed.returncode == 127 else _JS_FIX)
    try:
        data: object = json.loads(completed.stdout)
    except json.JSONDecodeError as exc:
        raise _failed(command, completed, _JSON_FIX) from exc
    files = _as_files(data, command=command, completed=completed)
    name = case_name if case_name is not None else (_case_name_from_output(files) or "case")
    return GeneratedCase(files=files, command=command, case_name=name)


def _case_name_from_output(files: dict[str, str]) -> str | None:
    for key, text in files.items():
        if key.endswith("/case.json") or key == "case.json":
            try:
                data: object = json.loads(text)
            except json.JSONDecodeError:
                return None
            if isinstance(data, dict):
                name = cast(dict[str, Any], data).get("caseName")
                if isinstance(name, str):
                    return name
    return None


def _apply_argv(spec_path: Path, *, case_name: str | None) -> list[str]:
    argv = _node_argv("--apply-spec", str(spec_path))
    if case_name is not None:
        argv.extend(["--name", case_name])
    return argv


def _node_argv(*args: str) -> list[str]:
    root = repository_root()
    script = root / "tests" / "headless.js"
    return [os.environ.get("FOAMSTUDIO_NODE", "node"), str(script), *args]


def _write_temp(text: str, *, suffix: str) -> Path:
    with tempfile.NamedTemporaryFile(
        "w",
        encoding="utf-8",
        newline="\n",
        suffix=suffix,
        prefix="foamstudio-",
        delete=False,
    ) as handle:
        handle.write(text)
        name = handle.name
    return Path(name)


def _run(argv: list[str], *, timeout: float) -> subprocess.CompletedProcess[str]:
    command = format_argv(argv)
    try:
        return subprocess.run(
            argv,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            cwd=repository_root(),
            timeout=timeout,
            check=False,
        )
    except FileNotFoundError as exc:
        raise GeneratorFailure(
            command=command,
            returncode=127,
            log_tail=str(exc),
            suggestion=NODE_INSTALL,
        ) from exc
    except OSError as exc:
        raise GeneratorFailure(
            command=command,
            returncode=126,
            log_tail=str(exc),
            suggestion=f"The generator process could not be started: {exc}",
        ) from exc
    except subprocess.TimeoutExpired as exc:
        stderr = exc.stderr if isinstance(exc.stderr, str) else ""
        stdout = exc.stdout if isinstance(exc.stdout, str) else ""
        raise GeneratorFailure(
            command=command,
            returncode=124,
            log_tail=log_tail(stdout, stderr),
            suggestion=(
                "The generator exceeded the time limit. Run the command above in a terminal "
                "to see where it stopped."
            ),
        ) from exc


def _failed(
    command: str,
    completed: subprocess.CompletedProcess[str],
    suggestion: str,
) -> GeneratorFailure:
    return GeneratorFailure(
        command=command,
        returncode=completed.returncode if completed.returncode is not None else 1,
        log_tail=log_tail(completed.stdout, completed.stderr),
        suggestion=suggestion,
    )


def _as_files(
    data: object,
    *,
    command: str,
    completed: subprocess.CompletedProcess[str],
) -> dict[str, str]:
    if not isinstance(data, dict) or not data:
        raise _failed(command, completed, _JSON_FIX)
    files: dict[str, str] = {}
    for key, value in cast(dict[str, Any], data).items():
        if not isinstance(key, str) or not isinstance(value, str):
            raise _failed(command, completed, _JSON_FIX)
        files[key] = value
    return files


_JS_FIX = (
    "The case generator rejected this case.json. The message above is from validateSpec "
    "in openfoam_case_generator.html. Fix the spec and run the command again."
)
_JSON_FIX = (
    "Node did not print a JSON map of case files. The command above should write only JSON "
    "to stdout. There is no second dictionary writer."
)
